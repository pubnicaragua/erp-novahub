function scheduleParentMapOverlayState(){
  if(window.parent===window||parentMapOverlayFrame)return;
  parentMapOverlayFrame=window.requestAnimationFrame(()=>{
    parentMapOverlayFrame=0;
    const selectors='#routeModal,#businessDetailOverlay,.modal-backdrop,.quick-capture';
    const open=[...document.querySelectorAll(selectors)].some(panel=>{
      if(panel.hidden)return false;
      const style=window.getComputedStyle(panel);
      return style.display!=='none'&&style.visibility!=='hidden';
    });
    if(parentMapOverlayState===open)return;
    parentMapOverlayState=open;
    window.parent.postMessage({source:'novahub-force-sales',type:'force-sales-map-overlay-state',open},window.location.origin);
  });
}
if(window.parent!==window){
  const mapOverlayObserver=new MutationObserver(scheduleParentMapOverlayState);
  document.querySelectorAll('#routeModal,#businessDetailOverlay,.modal-backdrop,.quick-capture').forEach(panel=>{
    mapOverlayObserver.observe(panel,{attributes:true,attributeFilter:['hidden','class','style']});
  });
  scheduleParentMapOverlayState();
}
